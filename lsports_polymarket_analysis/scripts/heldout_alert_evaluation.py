"""
heldout_alert_evaluation.py - Out-of-sample test of the LSports alert formula.

This script avoids single-match leakage:
- train model on fixtures from train dates
- choose alert threshold only on validation fixtures
- report final alert precision/recall/false alerts on held-out test fixtures

It uses compact feature/goal tables generated by batch_event_analysis.py.
"""
import _bootstrap  # noqa: F401
import argparse

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, roc_auc_score
from sklearn.preprocessing import StandardScaler

from src import load_config, resolve_path
from src.feature_engineering import feature_matrix
from src import signal_evaluation as SE


def _date_sets(args):
    train_dates = set(args.train_dates.split(","))
    val_dates = set(args.val_dates.split(","))
    test_dates = set(args.test_dates.split(","))
    return train_dates, val_dates, test_dates


def _fit_model(train: pd.DataFrame):
    X, y, cols = feature_matrix(train)
    scaler = StandardScaler()
    Xs = scaler.fit_transform(X)
    model = LogisticRegression(max_iter=1000, class_weight="balanced")
    model.fit(Xs, y)
    return model, scaler, cols


def _predict(model, scaler, frame: pd.DataFrame) -> np.ndarray:
    X, _, _ = feature_matrix(frame)
    pred = model.predict_proba(scaler.transform(X))[:, 1]
    return pd.Series(pred).rolling(3, min_periods=1).mean().to_numpy()


def _goals_for_fixture(goals: pd.DataFrame, fixture_id: str) -> pd.DataFrame:
    g = goals[goals["fixture_id"].astype(str) == str(fixture_id)].copy()
    if g.empty:
        return pd.DataFrame(columns=["ts"])
    g["ts"] = pd.to_datetime(g["goal_ts"], utc=True, format="mixed")
    return g.rename(columns={"goal_ts": "raw_goal_ts"})


def _score_many(frames: pd.DataFrame, goals: pd.DataFrame, pred_col: str,
                threshold: float, horizon_sec: int) -> dict:
    rows = []
    for fixture_id, fr in frames.groupby("fixture_id", sort=False):
        fr = fr.sort_values("ts").copy()
        hazard = fr[pred_col].to_numpy()
        g = _goals_for_fixture(goals, str(fixture_id))
        score = SE.score_threshold(fr, hazard, g, pd.DataFrame(),
                                   threshold, warning_sec=horizon_sec)
        score["fixture_id"] = str(fixture_id)
        score["n_goals"] = len(g)
        rows.append(score)
    per_fixture = pd.DataFrame(rows)
    total_alerts = int(per_fixture["n_alerts"].sum())
    total_true = int(per_fixture["true_alerts"].sum())
    total_false = int(per_fixture["false_alerts"].sum())
    total_goals = int(per_fixture["n_goals"].sum())
    weighted_recall_num = (per_fixture["goal_recall"].fillna(0) *
                           per_fixture["n_goals"]).sum()
    return {
        "threshold": threshold,
        "n_fixtures": int(per_fixture.shape[0]),
        "n_goals": total_goals,
        "n_alerts": total_alerts,
        "true_alerts": total_true,
        "false_alerts": total_false,
        "precision": total_true / total_alerts if total_alerts else np.nan,
        "goal_recall": weighted_recall_num / total_goals if total_goals else np.nan,
        "alerts_per_fixture": total_alerts / per_fixture.shape[0]
        if per_fixture.shape[0] else np.nan,
        "false_alerts_per_fixture": total_false / per_fixture.shape[0]
        if per_fixture.shape[0] else np.nan,
        "mean_goal_lead_sec": np.nanmean(per_fixture["mean_goal_lead_sec"])
        if per_fixture["mean_goal_lead_sec"].notna().any() else np.nan,
        "per_fixture": per_fixture,
    }


def _threshold_sweep(frames: pd.DataFrame, goals: pd.DataFrame, pred_col: str,
                     horizon_sec: int) -> pd.DataFrame:
    qs = np.arange(50, 99, 3)
    thresholds = np.unique(np.round(np.nanpercentile(frames[pred_col], qs), 4))
    rows = []
    for t in thresholds:
        score = _score_many(frames, goals, pred_col, float(t), horizon_sec)
        rows.append({k: v for k, v in score.items() if k != "per_fixture"})
    return pd.DataFrame(rows)


def _choose_threshold(sweep: pd.DataFrame, min_precision: float,
                      max_false_per_fixture: float) -> float:
    ok = sweep[(sweep["precision"] >= min_precision) &
               (sweep["false_alerts_per_fixture"] <= max_false_per_fixture) &
               (sweep["n_alerts"] > 0)]
    if ok.empty:
        ok = sweep[sweep["n_alerts"] > 0]
    if ok.empty:
        return float(sweep["threshold"].median())
    best = ok.sort_values(["goal_recall", "precision", "threshold"],
                          ascending=[False, False, False]).iloc[0] \
        if (ok["precision"] >= min_precision).any() else \
        ok.sort_values(["precision", "false_alerts_per_fixture", "threshold"],
                       ascending=[False, True, False]).iloc[0]
    return float(best["threshold"])


def _plot_sweep(val_sweep: pd.DataFrame, test_sweep: pd.DataFrame,
                chosen: float, out_path: str) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
    for ax, metric, ylabel in [
        (axes[0], "precision", "precision"),
        (axes[1], "false_alerts_per_fixture", "false alerts / fixture"),
    ]:
        ax.plot(val_sweep["threshold"], val_sweep[metric], marker="o",
                label="validation", color="#1c7ed6")
        ax.plot(test_sweep["threshold"], test_sweep[metric], marker="s",
                label="test", color="#2f9e44")
        ax.axvline(chosen, color="#e03131", ls="--", lw=1.2,
                   label="chosen threshold" if metric == "precision" else None)
        ax.set_xlabel("alert threshold")
        ax.set_ylabel(ylabel)
        ax.grid(alpha=0.25)
    axes[0].legend(fontsize=8)
    fig.suptitle("Held-out alert threshold tradeoff")
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def _plot_per_fixture(per_fixture: pd.DataFrame, out_path: str) -> None:
    if per_fixture.empty:
        return
    df = per_fixture.sort_values(["false_alerts", "true_alerts"],
                                 ascending=[False, False]).copy()
    fig, ax = plt.subplots(figsize=(12, 5))
    x = np.arange(len(df))
    ax.bar(x, df["true_alerts"], label="true alerts", color="#2f9e44")
    ax.bar(x, df["false_alerts"], bottom=df["true_alerts"],
           label="false alerts", color="#f08c00")
    ax.set_xticks(x)
    ax.set_xticklabels(df["fixture_id"], rotation=75, ha="right", fontsize=8)
    ax.set_ylabel("alert episodes")
    ax.set_title("Held-out test alert outcomes by fixture")
    ax.grid(axis="y", alpha=0.25)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def _plot_score_distribution(test: pd.DataFrame, chosen: float,
                             out_path: str) -> None:
    fig, ax = plt.subplots(figsize=(8, 4.5))
    pos = test[test["label_goal_next"] == 1]["hazard"]
    neg = test[test["label_goal_next"] == 0]["hazard"]
    ax.hist(neg, bins=40, alpha=0.65, label="no goal in horizon",
            color="#868e96", density=True)
    ax.hist(pos, bins=40, alpha=0.65, label="goal in horizon",
            color="#e03131", density=True)
    ax.axvline(chosen, color="#222", ls="--", lw=1.2,
               label="chosen threshold")
    ax.set_xlabel("out-of-sample hazard")
    ax.set_ylabel("density")
    ax.set_title("Held-out test hazard separation")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def main():
    cfg = load_config()
    ap = argparse.ArgumentParser()
    ap.add_argument("--features", default="data/processed/batch_features.parquet")
    ap.add_argument("--goals", default="outputs/tables/goal_event_summary.csv")
    ap.add_argument("--matches", default="outputs/tables/match_summary.csv")
    ap.add_argument("--train-dates", default="2026-05-24,2026-05-25,2026-05-26")
    ap.add_argument("--val-dates", default="2026-05-27")
    ap.add_argument("--test-dates", default="2026-05-28")
    ap.add_argument("--horizon-sec", type=int, default=120)
    ap.add_argument("--min-precision", type=float, default=0.5)
    ap.add_argument("--max-false-per-fixture", type=float, default=1.0)
    args = ap.parse_args()

    features = pd.read_parquet(resolve_path(args.features))
    goals = pd.read_csv(resolve_path(args.goals))
    matches = pd.read_csv(resolve_path(args.matches))
    features["fixture_id"] = features["fixture_id"].astype(str)
    features["ts"] = pd.to_datetime(features["ts"], utc=True, format="mixed")
    matches["fixture_id"] = matches["fixture_id"].astype(str)
    meta = matches[["fixture_id", "event_date", "home", "away", "league_name"]]
    features = features.merge(meta, on="fixture_id", how="left")

    train_dates, val_dates, test_dates = _date_sets(args)
    train = features[features["event_date"].isin(train_dates)].copy()
    val = features[features["event_date"].isin(val_dates)].copy()
    test = features[features["event_date"].isin(test_dates)].copy()
    if train.empty or val.empty or test.empty:
        raise SystemExit("Empty train/validation/test split.")

    model, scaler, cols = _fit_model(train)
    for name, frame in [("train", train), ("validation", val), ("test", test)]:
        frame["hazard"] = _predict(model, scaler, frame)
        y = frame["label_goal_next"].to_numpy()
        p = frame["hazard"].to_numpy()
        auc = roc_auc_score(y, p) if len(np.unique(y)) > 1 else np.nan
        ap_score = average_precision_score(y, p) if len(np.unique(y)) > 1 else np.nan
        print(f"{name}: rows={len(frame)} fixtures={frame.fixture_id.nunique()} "
              f"pos={int(y.sum())} auc={auc:.3f} ap={ap_score:.3f}")

    val_sweep = _threshold_sweep(val, goals, "hazard", args.horizon_sec)
    chosen = _choose_threshold(val_sweep, args.min_precision,
                               args.max_false_per_fixture)
    test_sweep = _threshold_sweep(test, goals, "hazard", args.horizon_sec)
    val_score = _score_many(val, goals, "hazard", chosen, args.horizon_sec)
    test_score = _score_many(test, goals, "hazard", chosen, args.horizon_sec)
    per_fixture = test_score["per_fixture"].merge(
        meta, on="fixture_id", how="left").sort_values("fixture_id")

    tdir = resolve_path(cfg["paths"]["table_dir"])
    fdir = resolve_path(cfg["paths"]["fig_dir"])
    rdir = resolve_path(cfg["paths"]["report_dir"])
    val_sweep.to_csv(f"{tdir}/heldout_alert_validation_thresholds.csv",
                     index=False, encoding="utf-8-sig")
    test_sweep.to_csv(f"{tdir}/heldout_alert_test_thresholds.csv",
                      index=False, encoding="utf-8-sig")
    per_fixture.to_csv(f"{tdir}/heldout_alert_test_by_fixture.csv",
                       index=False, encoding="utf-8-sig")
    summary = pd.DataFrame([
        {"split": "validation", **{k: v for k, v in val_score.items()
                                   if k != "per_fixture"}},
        {"split": "test", **{k: v for k, v in test_score.items()
                             if k != "per_fixture"}},
    ])
    summary.to_csv(f"{tdir}/heldout_alert_summary.csv",
                   index=False, encoding="utf-8-sig")

    _plot_sweep(val_sweep, test_sweep, chosen,
                f"{fdir}/heldout_alert_threshold_tradeoff.png")
    _plot_per_fixture(per_fixture,
                      f"{fdir}/heldout_alert_test_by_fixture.png")
    _plot_score_distribution(test, chosen,
                             f"{fdir}/heldout_alert_score_distribution.png")

    formula = [
        "# Held-Out LSports Alert Evaluation",
        "",
        "## Alert Formula",
        "",
        "The alert is not an LSports abnormal-match field. It is a model score "
        "computed from LSports event-flow features available at time `t`.",
        "",
        "For each fixture, the event stream is sampled every 30 seconds in this "
        "batch feature table. At each time `t`, features include current match "
        "minute, score state, period, cumulative cards, and rolling 60/180/300/600 "
        "second counts or xT-weighted sums for live events, attacks, dangerous "
        "attacks, shots, and corners.",
        "",
        "The training label is:",
        "",
        "`y_t = 1{a goal occurs in (t, t + 120 seconds]}`",
        "",
        "The fitted logistic hazard is:",
        "",
        "`hazard_t = sigmoid(beta_0 + sum_j beta_j * zscore(x_{t,j}))`",
        "",
        "The score is smoothed with a 3-step rolling mean. An alert episode starts "
        "when the smoothed score is above the chosen threshold. Repeated crossings "
        "within 90 seconds are collapsed into one episode.",
        "",
        "A true alert means a goal occurs within the next 120 seconds. A false "
        "alert means no goal occurs in that horizon.",
        "",
        "## Leakage Control",
        "",
        f"- Train dates: `{args.train_dates}`",
        f"- Validation dates for threshold selection: `{args.val_dates}`",
        f"- Final held-out test dates: `{args.test_dates}`",
        "- Test fixtures are not used for model fitting or threshold selection.",
        "",
        "## Summary",
        "",
        SE.markdown_table(summary),
        "",
        "## Selected Features",
        "",
        ", ".join(cols),
        "",
        "## Figures",
        "",
        "- `outputs/figures/heldout_alert_threshold_tradeoff.png`",
        "- `outputs/figures/heldout_alert_test_by_fixture.png`",
        "- `outputs/figures/heldout_alert_score_distribution.png`",
        "",
        "## Interpretation",
        "",
        "This is the first honest alert test. If precision is low or false alerts "
        "per fixture are high, the signal should be treated as a risk filter rather "
        "than a trading trigger. The next step is to combine this held-out LSports "
        "hazard with Polymarket BBO filters on mapped markets.",
    ]
    with open(f"{rdir}/heldout_alert_evaluation_report.md", "w", encoding="utf-8") as f:
        f.write("\n".join(formula) + "\n")

    print(f"chosen_threshold={chosen:.4f}")
    print(f"summary: {tdir}/heldout_alert_summary.csv")
    print(f"report: {rdir}/heldout_alert_evaluation_report.md")


if __name__ == "__main__":
    main()
